#!/usr/bin/env python3
"""
Generate the registry of statically linked GOAL C modules (see docs/3ds-port/c_backend.md).

goalc --instruction-set c writes one C file per object to out/<game>/csrc/. When those files are
compiled with -DGOALC_STATIC, each exports goalc_static_<name>(). This script writes a C file with
goalc_register_static_modules(), which registers all of them with the runtime.

usage: gen_c_registry.py <csrc dir> <output .c file> [<instance wrapper dir>]
       gen_c_registry.py --instances <list file> <csrc dir> <wrapper dir>

(AI-assisted) Module instances: when the same object file is in two level DGOs that can be loaded
at the same time, each loaded copy needs its own static data (segment bases), so the module is
compiled more than once. The list file has lines "<object name> <instances>" (# comments); for
each instance after the first, --instances writes <wrapper dir>/<name>.i<k>.c, which includes the
module's C file with its accessor renamed. The registry then registers every instance (the
runtime gives each loaded copy a free one).
"""

import os
import re
import sys

ACCESSOR = re.compile(r"^const GoalCModule\* (goalc_static_\w+)\(void\) \{", re.MULTILINE)
INSTANCE = re.compile(r"^// GOALC_INSTANCE (goalc_static_\w+)$", re.MULTILINE)


def write_if_changed(path, text):
    if os.path.exists(path):
        with open(path) as f:
            if f.read() == text:
                return
    with open(path, "w") as f:
        f.write(text)


def gen_instances(list_file, csrc, out_dir):
    os.makedirs(out_dir, exist_ok=True)
    wanted = {}
    with open(list_file) as f:
        for line in f:
            line = line.split("#", 1)[0].strip()
            if not line:
                continue
            name, count = line.split()
            wanted[name] = int(count)
    written = set()
    for name, count in sorted(wanted.items()):
        src = os.path.join(csrc, name + ".c")
        if not os.path.exists(src):
            print(f"warning: instances: no {src}")
            continue
        with open(src) as f:
            match = ACCESSOR.search(f.read())
        if not match:
            print(f"warning: {src} has no static module accessor")
            continue
        acc = match.group(1)
        for k in range(1, count):
            path = os.path.join(out_dir, f"{name}.i{k}.c")
            text = (
                f"// Generated by scripts/3ds/gen_c_registry.py: instance {k} of {name}. Do not edit.\n"
                f"// GOALC_INSTANCE {acc}_i{k}\n"
                f"#define {acc} {acc}_i{k}\n"
                f'#include "{os.path.abspath(src)}"\n'
            )
            write_if_changed(path, text)
            written.add(os.path.basename(path))
    for old in os.listdir(out_dir):
        if old.endswith(".c") and old not in written:
            os.remove(os.path.join(out_dir, old))
    print(f"{len(written)} extra module instances")
    return 0


def main():
    if len(sys.argv) == 5 and sys.argv[1] == "--instances":
        return gen_instances(sys.argv[2], sys.argv[3], sys.argv[4])
    if len(sys.argv) not in (3, 4):
        print(__doc__)
        return 1
    csrc, out_path = sys.argv[1], sys.argv[2]
    names = []
    for file_name in sorted(os.listdir(csrc)):
        if not file_name.endswith(".c"):
            continue
        with open(os.path.join(csrc, file_name)) as f:
            match = ACCESSOR.search(f.read())
        if not match:
            print(f"warning: {file_name} has no static module accessor")
            continue
        names.append(match.group(1))
    n_modules = len(names)
    if len(sys.argv) == 4 and os.path.isdir(sys.argv[3]):
        for file_name in sorted(os.listdir(sys.argv[3])):
            if file_name.endswith(".c"):
                with open(os.path.join(sys.argv[3], file_name)) as f:
                    names += INSTANCE.findall(f.read())

    lines = [
        "// Generated by scripts/3ds/gen_c_registry.py. Do not edit.",
        '#include "goal_c_abi.h"',
        "",
    ]
    lines += [f"const GoalCModule* {n}(void);" for n in names]
    lines += ["", "void goalc_register_static_modules(void) {"]
    lines += [f"  goalc_register_module({n}());" for n in names]
    lines += ["}", ""]
    with open(out_path, "w") as f:
        f.write("\n".join(lines))
    print(f"{n_modules} modules, {len(names) - n_modules} extra instances")
    return 0


if __name__ == "__main__":
    sys.exit(main())
