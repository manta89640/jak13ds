#!/usr/bin/env python3
# (AI-assisted)
# Writes game/graphics/ctr/keira_skeletons.inc: the bind poses of Jak's and Keira's skeletons
# (joint names, parents, world positions in meters) for the "play as Keira" easter egg
# (CtrKeiraRig.cpp). Input: the .glb files the decompiler writes with "rip_levels": true for
# GAME.CGO (decompiler_out/jak1/levels/common/eichar-lod0.glb) and VI1.DGO
# (decompiler_out/jak1/levels/village1/assistant-lod0.glb). Their skins carry the art groups'
# art-joint-geo bind poses (inverse bind matrices, level_extractor/fr3_to_gltf.cpp).
#
#   gen_keira_skeletons.py <eichar-lod0.glb> <assistant-lod0.glb> <out .inc>
import json
import struct
import sys

import numpy as np


def load_glb(path):
    d = open(path, "rb").read()
    json_len = struct.unpack_from("<I", d, 12)[0]
    j = json.loads(d[20 : 20 + json_len])
    off = 20 + json_len
    bin_len = struct.unpack_from("<I", d, off)[0]
    return j, d[off + 8 : off + 8 + bin_len]


def accessor(j, b, i):
    a = j["accessors"][i]
    bv = j["bufferViews"][a["bufferView"]]
    n = {"SCALAR": 1, "VEC2": 2, "VEC3": 3, "VEC4": 4, "MAT4": 16}[a["type"]]
    dt = {5126: np.float32, 5121: np.uint8, 5123: np.uint16, 5125: np.uint32}[a["componentType"]]
    o = bv.get("byteOffset", 0) + a.get("byteOffset", 0)
    return np.frombuffer(b, dtype=dt, count=a["count"] * n, offset=o).reshape(a["count"], n)


def skeleton(path):
    j, b = load_glb(path)
    skin = j["skins"][0]
    # column major in the file
    ibm = accessor(j, b, skin["inverseBindMatrices"]).reshape(-1, 4, 4).transpose(0, 2, 1)
    names = [j["nodes"][n]["name"] for n in skin["joints"]]
    index = {n: i for i, n in enumerate(skin["joints"])}
    parent = [-1] * len(names)
    for i, n in enumerate(skin["joints"]):
        for c in j["nodes"][n].get("children", []):
            if c in index:
                parent[index[c]] = i
    pos = [np.linalg.inv(m.astype(np.float64))[:3, 3] for m in ibm]
    return names, parent, pos


def main():
    if len(sys.argv) != 4:
        sys.exit(__doc__)
    out = [
        "// (AI-assisted) Bind poses of Jak's (eichar-lod0) and Keira's (assistant-lod0) skeletons: joint",
        "// name, parent (-1: none), world position at bind (meters), from the art groups' art-joint-geo",
        "// (decompiler level_extractor extract_joint_group, as the .glb export writes them). Generated by",
        "// tools/ctr_level_converter/gen_keira_skeletons.py; used by CtrKeiraRig.cpp.",
    ]
    for var, path in (("kJakSkeleton", sys.argv[1]), ("kKeiraSkeleton", sys.argv[2])):
        names, parent, pos = skeleton(path)
        out.append(f"static const KeiraSkelJoint {var}[] = {{")
        for i, (n, p, w) in enumerate(zip(names, parent, pos)):
            out.append(f'    {{"{n}", {p}, {{{w[0]:.6f}f, {w[1]:.6f}f, {w[2]:.6f}f}}}},  // {i}')
        out.append("};")
    open(sys.argv[3], "w").write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
