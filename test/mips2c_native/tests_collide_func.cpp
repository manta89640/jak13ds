void register_collide_func_tests() {
  add_test({"moving-sphere-triangle-intersect",
            "moving-sphere-triangle-intersect",
            20000,
            [] {
              bind_collide_functions();
              bind_mips2c_symbol("collide-do-primitives");
              bind_mips2c_symbol("moving-sphere-triangle-intersect");
            },
            gen_msti,
            {}});

  // (AI-assisted) the game's inputs, the functions collide-do-primitives calls being their native
  // code on the mips2c side too (as in the game, where they have no other version), called through
  // C mode's adapter
  add_test({"moving-sphere-triangle-intersect (game inputs)",
            "moving-sphere-triangle-intersect",
            (int)(sizeof(kGameMsti) / sizeof(kGameMsti[0])),
            [] {
              bind_collide_functions();
              bind_mips2c_symbol("collide-do-primitives");
              bind_mips2c_symbol("moving-sphere-triangle-intersect");
            },
            gen_msti_game,
            {},
            {"ray-sphere-intersect", "ray-cylinder-intersect"}});

  add_test({"collide-do-primitives",
            "collide-do-primitives",
            20000,
            [] {
              bind_collide_functions();
              bind_mips2c_symbol("collide-do-primitives");
            },
            [](Case& c) {
              gen_msti(c);
              // args 5-7 are whatever the caller had in t1-t3
              c.args[5] = c.g.u32_();
            },
            {}});
}

