//! one of kGameMsti
void gen_msti_game(Case& c) {
  const u32* k = kGameMsti[c.index % (int)(sizeof(kGameMsti) / sizeof(kGameMsti[0]))];
  c.args[0] = alloc(16);
  st_bytes(c.args[0], k, 16);
  c.args[1] = alloc(16);
  st_bytes(c.args[1], k + 4, 16);
  c.args[2] = f_bits(bits_f(k[8]));
  c.args[3] = alloc(64);
  st_bytes(c.args[3], k + 9, 48);
  st<u32>(c.args[3] + 48, k[21]);
  c.args[4] = alloc(16);  // out-point
  c.args[5] = alloc(16);  // out-normal
  c.args[6] = c.g.u32_();
  c.args[7] = c.g.u32_();
}

