#!/usr/bin/env python3
"""
(AI-assisted) The list of C modules that the 3DS build compiles more than once (module instances,
docs/3ds-port/c_backend.md): object files that are in two level DGOs that can be loaded at the
same time. Each loaded copy of such an object needs its own static data (segment bases), so the
runtime links each copy to its own instance of the module.

A pair of DGOs can be loaded together unless their levels' memory modes exclude each other in the
level heap (goal_src/jak2/engine/level/level.gc, level-get-for-use: large + small-edge,
medium + medium / small-edge, small-center + 2 small-edge; borrow levels live in another level's
heap). That is a static upper bound: it keeps every pair the level heap allows. GAME.CGO and
ART.CGO are never loaded together.

usage: module_instances.py [--game jak2] [--csrc DIR] > platform/3ds/jak2_module_instances.txt
"""

import argparse
import collections
import glob
import itertools
import os
import re
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", ".."))


def level_modes(game):
    src = open(os.path.join(ROOT, f"goal_src/{game}/engine/level/level-info.gc")).read()
    modes = {}
    for m in re.finditer(r"\(define (\S+)\s+\(new 'static 'level-load-info(.*?)(?=\n\(define |\Z)",
                         src, re.S):
        body = m.group(2)
        nick = re.search(r":nickname '(\S+)", body)
        mode = re.search(r"memory-mode \(load-buffer-mode (\S+)\)", body)
        if nick:
            modes[nick.group(1).upper()] = mode.group(1) if mode else "small-edge"
    return modes


def can_coload(a, b, modes):
    ma, mb = modes.get(a), modes.get(b)
    if ma is None or mb is None or "borrow" in (ma, mb):
        return True
    pair = {ma, mb}
    if "large" in pair:
        return ma == "small-edge" or mb == "small-edge"
    if "small-center" in pair:
        return pair == {"small-center", "small-edge"}
    return True  # medium / small-edge


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--game", default="jak2")
    ap.add_argument("--csrc", default="", help="only objects with a C module in this folder")
    ap.add_argument("--instances", type=int, default=2)
    args = ap.parse_args()
    modes = level_modes(args.game)
    objs = collections.defaultdict(set)
    for f in glob.glob(os.path.join(ROOT, f"goal_src/{args.game}/dgos/*.gd")):
        text = open(f).read()
        dgo = re.search(r'"([A-Z0-9]+)\.(DGO|CGO)"', text).group(1)
        for o in re.findall(r'"([^"]+)\.o"', text):
            objs[o].add(dgo)
    print(f"# (AI-assisted) generated by platform/3ds/tools/module_instances.py --game {args.game}")
    print("# <object> <instances>: object files in two level DGOs that can be loaded together")
    for o in sorted(objs):
        dgos = objs[o] - {"ART"} if "GAME" in objs[o] else objs[o]
        if len(dgos) < 2:
            continue
        if args.csrc and not os.path.exists(os.path.join(args.csrc, o + ".c")):
            continue
        if any(can_coload(a, b, modes) for a, b in itertools.combinations(sorted(dgos), 2)):
            print(f"{o} {args.instances}  # {' '.join(sorted(dgos))}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
